package main

import (
	"fmt"
	"strings"
)

// statusDoc renders STATUS.md. The output depends only on the registry, so the
// same input always gives the same bytes (no dates, no machine paths).
type statusDoc struct {
	reg    registry
	phases phasesFile
	b      strings.Builder
}

func renderStatus(reg registry, phases phasesFile) string {
	doc := &statusDoc{reg: reg, phases: phases}
	doc.header()
	doc.summary()
	doc.phaseSections()
	doc.demos()
	doc.otherEntries()
	doc.openDecisions()
	doc.openGaps()
	doc.divergences()
	return doc.b.String()
}

func (d *statusDoc) line(format string, args ...any) {
	fmt.Fprintf(&d.b, format+"\n", args...)
}

func (d *statusDoc) header() {
	d.line("# Roadmap status")
	d.line("")
	d.line("<!-- Generated by `make roadmap` (scripts/roadmapcheck) from docs/roadmap/features.yaml")
	d.line("     and docs/roadmap/phases.yaml. Do not edit by hand (ADR-0038). -->")
	d.line("")
	d.line("Source of truth: [`features.yaml`](features.yaml), [`phases.yaml`](phases.yaml).")
	d.line("Canonical decisions: [`canonical-spec.md`](canonical-spec.md). How it works: [`README.md`](README.md).")
	d.line("")
}

func (d *statusDoc) phaseFeatures(id int) []feature {
	var out []feature
	for _, item := range d.reg.Features {
		if item.Kind == kindRoadmap && item.Phase != nil && *item.Phase == id {
			out = append(out, item)
		}
	}
	return out
}

func (d *statusDoc) summary() {
	d.line("## Summary")
	d.line("")
	d.line("`done` counts only fully met features; `diverged` (all criteria met, scope changed by an ADR) is shown separately.")
	d.line("")
	d.line("| Phase | Name | P0 done | P1 done | P2 done | Exit criterion |")
	d.line("| --- | --- | --- | --- | --- | --- |")
	for _, item := range d.phases.Phases {
		features := d.phaseFeatures(item.ID)
		d.line("| %d | %s | %s | %s | %s | %s |", item.ID, item.Name,
			progress(features, "P0"), progress(features, "P1"), progress(features, "P2"), item.ExitStatus)
	}
	d.line("")
}

func progress(features []feature, priority string) string {
	total, done, diverged := 0, 0, 0
	for _, item := range features {
		if item.Priority != priority {
			continue
		}
		total++
		switch item.Status {
		case statusDone:
			done++
		case statusDiverged:
			diverged++
		}
	}
	if total == 0 {
		return "-"
	}
	text := fmt.Sprintf("%d/%d (%d%%)", done, total, done*100/total)
	if diverged > 0 {
		text += fmt.Sprintf(" +%d diverged", diverged)
	}
	return text
}

func (d *statusDoc) phaseSections() {
	for _, item := range d.phases.Phases {
		d.line("## Phase %d - %s (%s)", item.ID, item.Name, item.Release)
		d.line("")
		d.line("**Exit criterion (%s):** %s", item.ExitStatus, item.ExitCriterion)
		if item.Note != "" {
			d.line("")
			d.line("Note: %s", item.Note)
		}
		d.line("")
		d.featureTable(d.phaseFeatures(item.ID))
	}
}

func (d *statusDoc) featureTable(features []feature) {
	d.line("| ID | Feature | Priority | Status | Criteria met | Issues |")
	d.line("| --- | --- | --- | --- | --- | --- |")
	for _, item := range features {
		d.line("| %s | %s | %s | %s | %s | %s |", linkSpec(item), item.Name, item.Priority, item.Status,
			criteriaMet(item), issues(item.Tasks))
	}
	d.line("")
}

func linkSpec(item feature) string {
	if item.Spec == "" {
		return item.ID
	}
	return fmt.Sprintf("[%s](../../%s)", item.ID, item.Spec)
}

func criteriaMet(item feature) string {
	if len(item.Acceptance) == 0 {
		return "-"
	}
	met := 0
	for _, ac := range item.Acceptance {
		if ac.Status == criterionMet {
			met++
		}
	}
	return fmt.Sprintf("%d/%d", met, len(item.Acceptance))
}

func issues(numbers []int) string {
	if len(numbers) == 0 {
		return ""
	}
	parts := make([]string, len(numbers))
	for i, number := range numbers {
		parts[i] = fmt.Sprintf("#%d", number)
	}
	return strings.Join(parts, ", ")
}

func (d *statusDoc) demos() {
	d.line("## Demo milestones")
	d.line("")
	d.line("| Demo | Name | Status | Features | Note |")
	d.line("| --- | --- | --- | --- | --- |")
	for _, item := range d.phases.Demos {
		d.line("| %s | %s | %s | %s | %s |", item.ID, item.Name, item.Status, strings.Join(item.Features, ", "), item.Note)
	}
	d.line("")
}

func (d *statusDoc) otherEntries() {
	d.line("## Derived, enabler and future entries")
	d.line("")
	d.line("| ID | Name | Kind | Parent | Status | Note |")
	d.line("| --- | --- | --- | --- | --- | --- |")
	for _, item := range d.reg.Features {
		if item.Kind != kindRoadmap {
			d.line("| %s | %s | %s | %s | %s | %s |", linkSpec(item), item.Name, item.Kind, item.Parent, item.Status, item.Note)
		}
	}
	d.line("")
}

func (d *statusDoc) openDecisions() {
	d.line("## Open decisions (`needs_decision`)")
	d.line("")
	if len(d.reg.NeedsDecision) == 0 {
		d.line("None.")
	}
	for _, item := range d.reg.NeedsDecision {
		d.line("- **%s** (%s): %s", item.ID, item.Feature, item.Text)
	}
	d.line("")
}

func (d *statusDoc) openGaps() {
	d.line("## Open criteria")
	d.line("")
	d.line("Open acceptance criteria of features that are not `not_started` or `deferred`.")
	d.line("")
	d.line("| Criterion | Text | Issue | Note |")
	d.line("| --- | --- | --- | --- |")
	for _, item := range d.reg.Features {
		if item.Status == statusNotStarted || item.Status == statusDeferred {
			continue
		}
		for _, ac := range item.Acceptance {
			if ac.Status == criterionOpen {
				d.line("| %s | %s | %s | %s |", ac.ID, ac.Text, issueRef(ac.Issue), ac.Note)
			}
		}
	}
	d.line("")
}

func issueRef(number int) string {
	if number == 0 {
		return ""
	}
	return fmt.Sprintf("#%d", number)
}

func (d *statusDoc) divergences() {
	d.line("## Active divergences")
	d.line("")
	d.line("| Feature | Divergence | ADR | Issue | Deferred to |")
	d.line("| --- | --- | --- | --- | --- |")
	for _, entry := range d.reg.Features {
		for _, item := range entry.Divergences {
			d.line("| %s | %s | %s | %s | %s |", entry.ID, item.Text, item.ADR, issueRef(item.Issue), item.DeferredTo)
		}
	}
}
