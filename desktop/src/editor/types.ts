import type { Diagnostic } from '../types'

// Wire shapes of the graph document API (ADR-0021). The sidecar owns every graph
// rule; the editor only sends text and operations and renders what comes back.

export interface PortDef {
  type: string
  required?: boolean
}
export interface LoopDef {
  max_attempts?: number
  gate: { inputs?: Record<string, PortDef>; config?: Record<string, unknown> }
  bindings: EdgeDef[]
}
export interface NodeDef {
  type: string
  inputs?: Record<string, PortDef>
  outputs?: Record<string, PortDef>
  config?: Record<string, unknown>
  loop?: LoopDef
}
export interface EdgeDef {
  from: string
  to: string
}
/** The parsed graph as the engine reports it. Only what the canvas draws is typed. */
export interface Definition {
  id: string
  name?: string
  metadata?: Record<string, unknown>
  inputs?: Record<string, PortDef>
  nodes: Record<string, NodeDef>
  edges: EdgeDef[]
  graph_input_bindings?: EdgeDef[]
  outputs: Record<string, { from: string }>
}

/** A JSON value an operation carries into the file (set_config, set_loop). */
export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue }

export type PortDirection = 'input' | 'output'

/** Operations of ADR-0020 (ops_version 1) the canvas and the inspector send. Field names are the Go ones. */
export type Op =
  | { op: 'add_node'; id: string; type: string }
  | { op: 'remove_node'; id: string }
  | { op: 'rename_node'; id: string; new_id: string }
  | { op: 'set_layout'; nodes: Record<string, { x: number; y: number }> }
  | { op: 'add_edge' | 'remove_edge' | 'can_connect'; from: string; to: string }
  // F2.3 graph data operations: graph input bindings and the connection query (from: an output or inputs.NAME, or to: an input)
  | { op: 'add_graph_input_binding' | 'remove_graph_input_binding'; from: string; to: string }
  | { op: 'list_connections'; from: string }
  | { op: 'list_connections'; to: string }
  // F2.2 inspector operations
  | { op: 'set_config'; node: string; path: string[]; value: JsonValue }
  | { op: 'unset_config'; node: string; path: string[] }
  | { op: 'add_port'; node: string; direction: PortDirection; port: string; type: string; required?: boolean }
  | { op: 'update_port'; node: string; direction: PortDirection; port: string; new_port?: string; type?: string; required?: boolean }
  | { op: 'remove_port'; node: string; direction: PortDirection; port: string }
  | { op: 'set_loop'; node: string; max_attempts?: number; gate: { inputs?: Record<string, PortDef>; config: Record<string, JsonValue> }; bindings: EdgeDef[] }
  | { op: 'clear_loop'; node: string }
  | { op: 'set_units'; units: string[] }
  // Targeted loop edits: each patches one part of an existing loop in place.
  | { op: 'set_loop_attempts'; node: string; max_attempts?: number }
  | { op: 'set_loop_config'; node: string; path: string[]; value: JsonValue }
  | { op: 'unset_loop_config'; node: string; path: string[] }
  | { op: 'set_loop_gate_input'; node: string; port: string; type: string; required?: boolean }
  | { op: 'remove_loop_gate_input'; node: string; port: string }
  | { op: 'set_loop_bindings'; node: string; bindings: EdgeDef[] }

// ---- F2.2 field descriptors, generated by the sidecar from the Go validators ----

/** A condition on the node being edited: a config key (with a value) or a declared input. */
export interface Rule {
  key?: string
  equals?: string
  input?: string
}

export type FieldKind = 'string' | 'text' | 'bool' | 'int' | 'enum' | 'list' | 'map' | 'input_name' | 'path_list' | 'scalar' | 'group'

export interface FieldDescriptor {
  id: string
  key?: string
  kind: FieldKind
  required?: boolean
  default?: unknown
  enum?: string[]
  min?: number
  max?: number
  max_bytes?: number
  max_items?: number
  format?: string
  item?: FieldDescriptor
  input_types?: string[]
  input_required?: boolean
  fields?: FieldDescriptor[]
  requires?: Rule[]
  excludes?: Rule[]
  locked?: { value: unknown; reason: string }
}

export interface OutputPortDescriptor {
  name: string
  type: string
  required?: boolean
  requires?: Rule[]
}

export interface NodeTypeDescriptor {
  config: FieldDescriptor[]
  outputs: OutputPortDescriptor[]
  outputs_locked: boolean
  loop?: { fields: FieldDescriptor[]; gate: FieldDescriptor[]; gate_kinds: string[] }
}

/** A config key the form cannot show: unknown to the descriptors, or a value its control cannot hold. */
export interface AdvancedEntry {
  key: string
  yaml: string
  reason: 'unknown' | 'shape'
}

export interface NodeInfo {
  known_type: boolean
  advanced: AdvancedEntry[]
  loop_advanced?: AdvancedEntry[]
  independent_of: string[]
}

/** One counterpart port of a list_connections answer: the engine's verdict for that pair. */
export interface ConnectionOption {
  ref: string
  type: string
  required: boolean
  ok: boolean
  code?: string
  message?: string
}

export interface QueryResult {
  ok: boolean
  code?: string
  message?: string
  /** Only list_connections answers carry it; the engine omits an empty list. */
  options?: ConnectionOption[]
}

export interface OpResult {
  index: number
  op: string
  query?: QueryResult
}

export interface OpError {
  code: string
  message: string
  op_index: number
  node?: string
  edge?: string
  suggestion?: string
}

export interface OpenResponse {
  text: string
  hash: string
  version?: string
  definition?: Definition
  results?: OpResult[]
  diagnostics: Diagnostic[]
  parse_error?: string
  parse_line?: number
  parse_column?: number
  readonly_canvas: boolean
  readonly_reasons?: string[]
  line_ending: 'lf' | 'crlf'
  label: string
  node_types?: Record<string, NodeTypeDescriptor>
  node_info?: Record<string, NodeInfo>
}

export interface ValidateResponse {
  status: 'valid' | 'invalid'
  diagnostics: Diagnostic[]
  parse_error?: string
  parse_line?: number
  parse_column?: number
  version?: string
  definition?: Definition
  readonly_canvas?: boolean
  readonly_reasons?: string[]
  node_types?: Record<string, NodeTypeDescriptor>
  node_info?: Record<string, NodeInfo>
}

export type SaveOutcome =
  | { kind: 'saved'; hash: string }
  | { kind: 'conflict'; currentHash: string }
  | { kind: 'exists' }
  | { kind: 'gone' }
  | { kind: 'failed'; code: string; message: string }

export interface StatResponse {
  exists: boolean
  hash?: string
  size?: number
}
